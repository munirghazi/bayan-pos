// Regional-indicator flag from a 2-letter ISO code (e.g. 'SA' -> 🇸🇦).
export function flagOf(iso) {
  return (iso || '')
    .toUpperCase()
    .replace(/./g, (ch) => String.fromCodePoint(127397 + ch.charCodeAt(0)));
}

// Validate a LOCAL (no dial code) number for a country. Strict for KSA mobiles,
// permissive elsewhere (E.164-ish: 6–14 digits).
export function validateLocalPhone(iso, local) {
  if (iso === 'SA') return /^5\d{8}$/.test(local);
  return /^\d{6,14}$/.test(local);
}
